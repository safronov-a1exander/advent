// Package profile — персонализация ассистента (день 12).
//
// Самый частый вопрос дня в чате курса был «чем профиль отличается от
// памяти», и ведущий разводил их трижды. Короткий ответ: память — это то,
// что агент **накопил**, общаясь с пользователем; профиль — то, **как мы
// заставляем агента работать** под конкретного пользователя и конкретную
// задачу. Память пишет агент, профиль пишет человек. Память — данные,
// профиль — конфиг оркестрации.
//
// # Профиль — это markdown
//
// Профиль живёт в `profiles/<id>.md`. Тело файла — обычная проза: кто
// собеседник, как с ним разговаривать, чего делать нельзя. Ровно этот
// текст уходит в системный промпт.
//
// Первая версия была YAML со схемой: `style.address`, `style.tone`,
// `style.length`, `style.format`, `style.level`, `goal`, `limits` — семь
// полей, которые читались ровно в одном месте и склеивались там в те же
// прозаические строки. Схема ничего не проверяла и ни на что не влияла,
// зато заставляла брать в кавычки каждую фразу с двоеточием. Это та же
// ошибка, что позже случилась с инвариантами: текст, разложенный по полям
// ради вида структурности.
//
// Настоящие инструменты делают ровно так же, как здесь: `CLAUDE.md`,
// `.cursor/rules/*.mdc` — прозаический текст с необязательным frontmatter.
//
// # Дороги
//
// Frontmatter — единственная часть, где структура настоящая: дороги.
// «Профиль = пайплайн из скиллов для той или иной задачи», как формулировал
// курс: фича идёт через сбор требований, план, код и валидацию, а баг —
// через репродьюс, root cause и фикс. У дороги есть стадии, свой класс
// модели и своя стратегия рассуждения — это машинные данные, и они
// структурой и остаются.
//
// Какая дорога подходит запросу, решает короткий вызов модели. Раньше
// решал список слов-триггеров (`when: [упал, таймаут]`), и это был тот же
// изъян, что у инвариантов: «у нас всё легло» и «мы уронили прод» — один
// и тот же запрос для человека и два разных для подстроки. Теперь в дороге
// написано прозой, когда она уместна, а выбирает модель.
package profile

import (
	"fmt"
	"strings"
)

// Profile — настройка агента под конкретного пользователя.
type Profile struct {
	// ID — имя файла: profiles/<id>.md.
	ID string `yaml:"-"`
	// Name — человеческое имя для списков; по умолчанию — имя файла.
	Name string `yaml:"name"`
	// About — тело markdown-файла: кто собеседник и как ему отвечать.
	// Это и есть профиль; всё остальное — служебное.
	About string `yaml:"-"`

	// Pipelines — дороги под разные типы запросов. Первая в списке —
	// дорога по умолчанию: ею идёт всё, что не подошло остальным.
	Pipelines []Pipeline `yaml:"pipelines"`
}

// Pipeline — дорога запроса: какие стадии, каким классом модели и какой
// стратегией рассуждения.
type Pipeline struct {
	Name string `yaml:"name"`
	// When — когда эта дорога уместна, прозой. Пусто у дороги
	// по умолчанию. Текст читает не код, а модель, которая выбирает
	// дорогу: «у нас всё легло» и «мы уронили прод» — один и тот же
	// запрос по смыслу и два разных для списка слов.
	When string `yaml:"when"`
	// Stages — стадии дороги. Пока это описание: на тринадцатом дне по нему
	// поедет конечный автомат, а сейчас стадии видны в промпте и в отчёте,
	// чтобы модель знала, где она находится.
	Stages []string `yaml:"stages"`
	// Strategy — стратегия рассуждения дня 3 на этой дороге.
	Strategy string `yaml:"strategy"`
	// Tier — класс модели дня 5. Разные модели на разные дороги — это то,
	// «что не даёт модели самой себе поддакивать».
	Tier string `yaml:"tier"`
	// System — что дописать в системный промпт именно на этой дороге.
	System string `yaml:"system"`
}

// Default — дорога по умолчанию.
func (p *Profile) Default() (Pipeline, bool) {
	if p == nil || len(p.Pipelines) == 0 {
		return Pipeline{}, false
	}
	return p.Pipelines[0], true
}

// ByName — дорога по имени; так результат выбора превращается в дорогу.
func (p *Profile) ByName(name string) (Pipeline, bool) {
	if p == nil {
		return Pipeline{}, false
	}
	name = strings.TrimSpace(strings.ToLower(name))
	for _, pl := range p.Pipelines {
		if strings.ToLower(pl.Name) == name {
			return pl, true
		}
	}
	return p.Default()
}

// NeedsChoice — есть ли из чего выбирать. Одна дорога — выбирать нечего,
// и вызов делать не за что.
func (p *Profile) NeedsChoice() bool { return p != nil && len(p.Pipelines) > 1 }

// Block — профиль для системного промпта.
//
// Это тело markdown-файла как есть. Никакой сборки из полей: то, что
// написал человек, — то и читает модель.
func (p *Profile) Block() string {
	if p == nil {
		return ""
	}
	about := strings.TrimSpace(p.About)
	if about == "" {
		return ""
	}
	return "Профиль пользователя — так ты отвечаешь именно ему:\n" + about
}

// StageBlock — стадии выбранной дороги для системного промпта.
//
// Отдельным блоком, а не внутри профиля: профиль у пользователя один,
// а дорога зависит от запроса, и держать их врозь честнее — видно, что
// меняется от запроса к запросу, а что нет.
func (pl Pipeline) StageBlock() string {
	if len(pl.Stages) == 0 && strings.TrimSpace(pl.System) == "" {
		return ""
	}
	var b strings.Builder
	if len(pl.Stages) > 0 {
		fmt.Fprintf(&b, "Такие запросы у этого пользователя идут дорогой «%s»: %s.\n",
			pl.Name, strings.Join(pl.Stages, " → "))
		b.WriteString("Держись этого порядка и не перепрыгивай стадии.")
	}
	if s := strings.TrimSpace(pl.System); s != "" {
		if b.Len() > 0 {
			b.WriteString("\n")
		}
		b.WriteString(s)
	}
	return b.String()
}

// Summary — однострочная подпись профиля для шапки и отчётов.
func (p *Profile) Summary() string {
	if p == nil {
		return ""
	}
	name := p.Name
	if name == "" {
		name = p.ID
	}
	if len(p.Pipelines) == 0 {
		return name
	}
	return fmt.Sprintf("%s · дорог %d", name, len(p.Pipelines))
}

// Validate — что профиль вообще осмысленный. Зовётся при чтении файла:
// тихо не работающий профиль хуже, чем отказ его прочитать.
func (p *Profile) Validate() error {
	if strings.TrimSpace(p.About) == "" {
		return fmt.Errorf("профиль %q: пустое тело файла — нечего подмешивать в запрос", p.ID)
	}
	seen := map[string]bool{}
	for i, pl := range p.Pipelines {
		if strings.TrimSpace(pl.Name) == "" {
			return fmt.Errorf("профиль %q: у дороги %d нет имени", p.ID, i+1)
		}
		key := strings.ToLower(pl.Name)
		if seen[key] {
			// Имя дороги — то, что возвращает выбирающая модель; два
			// одинаковых имени сделали бы её ответ неразличимым.
			return fmt.Errorf("профиль %q: две дороги с именем %q", p.ID, pl.Name)
		}
		seen[key] = true
		if i > 0 && strings.TrimSpace(pl.When) == "" {
			// Дорога без описания «когда» никогда не будет выбрана, кроме
			// первой: молча мёртвая ветка конфига — худший вид сюрприза.
			return fmt.Errorf("профиль %q: у дороги %q нет when — по чему её выбирать?", p.ID, pl.Name)
		}
	}
	return nil
}
