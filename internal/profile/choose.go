package profile

import (
	"encoding/json"
	"fmt"
	"strings"
)

// Выбор дороги (день 12).
//
// Какая дорога подходит запросу — вопрос о смысле запроса, и решает его
// модель. Первая версия решала списком слов-триггеров (`when: [упал,
// таймаут]`), и это тот же изъян, что был у проверки инвариантов: «у нас
// всё легло», «мы уронили прод» и «сервис не отвечает» — один и тот же
// запрос для человека и три разных для подстроки. Добавлять синонимы можно
// бесконечно и всё равно не угадать.
//
// Вызов короткий: список дорог с описаниями и одна реплика пользователя,
// на выходе одно имя. Он идёт только когда дорог больше одной — при
// единственной дороге выбирать не из чего и платить не за что.
//
// Ошибка выбора дёшева и видна: в ленте перед ответом написано, какой
// дорогой пошёл запрос, а при любом сбое берётся дорога по умолчанию.
// Это и отличает выбор дороги от проверки инвариантов: там ошибка молча
// переписывала ответ, здесь она в худшем случае отправляет запрос
// обычным путём.

// ChooseSystem — инструкция выбирающему.
const ChooseSystem = `Ты распределяешь запросы пользователя по рабочим дорогам ассистента.

Тебе дают список дорог с описанием, когда каждая уместна, и сообщение пользователя.
Верни JSON: {"road": "имя дороги"}

Правила:
- выбирай по смыслу запроса, а не по совпадению слов;
- имя возвращай точно так, как оно написано в списке;
- если ни одна дорога явно не подходит — верни дорогу по умолчанию (она помечена в списке);
- ничего не объясняй, только JSON.`

// ChoosePrompt — тело запроса: дороги с описаниями и реплика.
func ChoosePrompt(p *Profile, query string) string {
	var b strings.Builder
	b.WriteString("Дороги:\n")
	for i, pl := range p.Pipelines {
		when := strings.TrimSpace(pl.When)
		if i == 0 {
			mark := "по умолчанию"
			if when != "" {
				mark += "; " + when
			}
			fmt.Fprintf(&b, "- %s (%s)\n", pl.Name, mark)
			continue
		}
		fmt.Fprintf(&b, "- %s: %s\n", pl.Name, when)
	}
	fmt.Fprintf(&b, "\nСообщение пользователя:\n%s", strings.TrimSpace(query))
	return b.String()
}

// ParseChoice читает ответ выбирающего и возвращает имя дороги.
// Пустое имя означает «берите дорогу по умолчанию».
func ParseChoice(raw string) (string, error) {
	raw = strings.TrimSpace(raw)
	raw = strings.TrimPrefix(raw, "```json")
	raw = strings.TrimSuffix(strings.TrimPrefix(raw, "```"), "```")
	var r struct {
		Road string `json:"road"`
	}
	if err := json.Unmarshal([]byte(strings.TrimSpace(raw)), &r); err != nil {
		return "", fmt.Errorf("выбор дороги не в JSON: %w", err)
	}
	return strings.TrimSpace(r.Road), nil
}
