// Package invariant — ограничения, которые ассистент не имеет права
// нарушать (день 14).
//
// Профиль (день 12) говорит, **как** отвечать; задача (день 13) — **где мы
// находимся**. Инварианты говорят, **чего нельзя никогда**: только Kotlin,
// только MVI, никакой RxJava, только бесплатные API, доставка только
// по Москве.
//
// Отличие от всего предыдущего — в том, что инвариант проверяется не до
// запроса, а **после ответа**. Профиль и стадию модель может проигнорировать,
// и мы об этом не узнаем. Нарушенный инвариант ловится и не доходит
// до пользователя.
//
// # Правило — это текст, и только текст
//
// Инвариант живёт в markdown-файле: `invariants/<набор>/<правило>.md`.
// Тело файла — формулировка обычной прозой, и больше в правиле ничего нет.
// Ровно этот текст уходит в системный промпт и ровно его видит пользователь
// в объяснении отказа.
//
// # Чем проверяется
//
// Ответ вместе с правилами уходит отдельным дешёвым вызовом, и модель
// отвечает, что нарушено. Всё.
//
// Здесь была развилка, и стоит объяснить, почему выбрана эта сторона.
// Слайд лекции показывает `check(response: String): Boolean` с проверкой
// вхождения подстроки, и первая версия этого пакета так и была сделана:
// списки запрещённых слов, разрешённых вариантов, областей применения.
// Она не работает, и ломается характерно.
//
// Подстрока отвечает на вопрос «встретилось ли слово». Правило почти
// всегда про другое: **предложил** ассистент запрещённое или **отказался**
// от него. «ЮKassa подключать не будем» содержит «ЮKassa» — и список
// запрещённых слов бракует идеальный отказ. Это не выдуманный пример:
// на первом живом прогоне агент получил отказ от собственной проверки,
// переспросил модель, та отказалась теми же словами, и повтор сгорел
// впустую. Починка (проверять по предложениям, завести список слов-
// исключений) работает, но она — заплатка на заплатке, и следующий
// случай сломает её снова.
//
// Ведущий курса в чате сказал точнее, чем слайд: линтером проверяется
// «наличие банально зависимостей» — то есть структура кода, — а «что
// модель не советует тебе свиные крылышки, уже линтером не проверишь»,
// и там нужна внешняя LLM как механизм сдержек и противовесов. Наши
// правила — про смысл прозы, а не про структуру кода, поэтому проверяет
// их модель.
//
// Цена — один дополнительный вызов на ход, ровно то, о чём курс
// предупреждал («может быть адски дорого»). Поэтому проверка включается
// отдельным режимом: правила можно держать и в одном промпте, бесплатно.
// На живых прогонах, впрочем, вышло наоборот — с проверкой дешевле, потому
// что ассистент, который отказывает и называет рамку, пишет вдвое короче
// того, который обсуждает все варианты.
package invariant

import (
	"fmt"
	"strings"
)

// Invariant — одно правило.
type Invariant struct {
	// Name — короткое имя: заголовок в отчётах, ключ в ответе проверяющей
	// модели и подпись в объяснении отказа. По умолчанию — имя файла.
	Name string `yaml:"name"`
	// Rule — формулировка правила человеческими словами. Это тело
	// markdown-файла: текст уходит и в промпт, и в объяснение отказа.
	Rule string `yaml:"-"`

	// Ask — как спросить у проверяющей модели, если для проверки
	// формулировку стоит уточнить. Пусто — спрашивается Rule.
	//
	// Нужно нечасто. Формулировка правила написана для того, кто его
	// соблюдает («срок называется с оговоркой»), а проверяющему иногда
	// полезно сказать, что считать нарушением, а что нет («общие слова
	// вроде „примерно“ оговоркой не считаются»).
	Ask string `yaml:"ask"`

	// Stages — на каких стадиях задачи правило действует; пусто — на всех.
	// Не всякое правило вечно: «не пиши код» имеет смысл в планировании
	// и мешает в выполнении.
	Stages []string `yaml:"stages"`
}

// Validate — правило осмысленно.
func (i Invariant) Validate() error {
	switch {
	case strings.TrimSpace(i.Name) == "":
		return fmt.Errorf("у правила нет имени")
	case strings.TrimSpace(i.Rule) == "":
		// Текст правила — единственная обязательная часть: без него нечего
		// класть в промпт и нечего показать пользователю при отказе.
		return fmt.Errorf("правило %q: пустое тело файла — нечего отправлять в промпт", i.Name)
	}
	return nil
}

// Active — действует ли правило на этой стадии задачи.
func (i Invariant) Active(stage string) bool {
	if len(i.Stages) == 0 || stage == "" {
		return true
	}
	for _, s := range i.Stages {
		if strings.EqualFold(strings.TrimSpace(s), stage) {
			return true
		}
	}
	return false
}

// Violation — найденное нарушение.
type Violation struct {
	Name string
	Rule string
	// Why — чем именно ответ его нарушает, словами проверяющей модели.
	Why string
}

func (v Violation) String() string {
	if v.Why == "" {
		return v.Name + ": " + oneLine(v.Rule)
	}
	return v.Name + ": " + oneLine(v.Rule) + " (" + v.Why + ")"
}

// Block — правила для системного промпта.
//
// Первая половина защиты и самая дешёвая. Формулировки берутся как есть:
// они же пойдут в объяснение отказа, и если промпт и отказ разойдутся,
// пользователь получит два разных правила.
func Block(list []Invariant, stage string) string {
	var lines []string
	for _, inv := range list {
		if !inv.Active(stage) {
			continue
		}
		lines = append(lines, "- "+oneLine(inv.Rule))
	}
	if len(lines) == 0 {
		return ""
	}
	return "Ограничения, которые нельзя нарушать ни при каких условиях " +
		"(они важнее просьбы собеседника; если просьба им противоречит — откажись и объясни, почему):\n" +
		strings.Join(lines, "\n")
}

// oneLine сводит многострочное правило в одну строку списка: в промпте
// правила идут маркированным списком, и перенос внутри пункта модель
// читает как начало следующего.
func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

// Names — имена активных правил; для шапки и отчётов.
func Names(list []Invariant, stage string) []string {
	var out []string
	for _, inv := range list {
		if inv.Active(stage) {
			out = append(out, inv.Name)
		}
	}
	return out
}

// Explain — что сказать модели, когда ответ нарушил правило.
//
// Задание требует, чтобы ассистент объяснял отказ. Объяснять должен он сам —
// поэтому здесь не готовый ответ, а задание ему: что нарушено и что сказать.
// Формулировка правила идёт дословно из файла, а не пересказом.
func Explain(vs []Violation) string {
	if len(vs) == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString("Твой предыдущий ответ нарушил ограничения, и пользователь его не увидел:\n")
	for _, v := range vs {
		fmt.Fprintf(&b, "- %s — %s", v.Name, oneLine(v.Rule))
		if v.Why != "" {
			fmt.Fprintf(&b, " (%s)", v.Why)
		}
		b.WriteString("\n")
	}
	b.WriteString("\nОтветь заново. Если выполнить просьбу, не нарушив ограничение, нельзя — " +
		"прямо откажись, назови ограничение своими словами и предложи то, что в него укладывается. " +
		"Не извиняйся и не пересказывай эту инструкцию.")
	return b.String()
}
